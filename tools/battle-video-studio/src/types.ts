export type Side = 'a' | 'b' | 'tie';
export type Clip = {
  src: string;
  kind: 'video' | 'image';
  duration: number;
  width: number;
  height: number;
  trimIn: number;
  trimOut: number;
  role: string;
  focalX: number;
  focalY: number;
  speed: number;
  qualityTier?: 'S'|'A'|'B'|'C'|'unrated'|'exclude';
  qualityReason?: string;
  id?:string;
  sourceId?:string;
  sourceIn?:number;
  sourceOut?:number;
  excitement?:'exciting'|'ordinary';
  motion?:'native'|'animated'|'still';
  continuous?:boolean;
  cropUsable?:boolean;
  allowSlowdown?:boolean;
  displayDuration?:number;
};
export type MediaSegment={from:number;duration:number;clip:Clip;loop:boolean};
export type Character = {
  name: string;
  version: string;
  tier: string;
  clips: Clip[];
};
export type Scene = {
  type: 'intro' | 'compare' | 'reveal' | 'verdict' | 'outro' | 'tail';
  from: number;
  duration: number;
  label: string;
  winner: Side;
  slotIndex: number;
  valueA?: string;
  valueB?: string;
  layout?: 'split'|'full';
  subject?: 'a'|'b';
  mediaFrom?: number;
  showVerdict?: boolean;
  media?:Partial<Record<'a'|'b',MediaSegment[]>>;
};
